# -*- coding: utf-8 -*-
"""build_rtm.py -- W8, the requirements traceability matrix, generated from the files it traces.

PURPOSE
  Traces each business objective (W1) through the decisions that serve it, the rules those decisions create, the stories
  that specify them and the UAT rows that test them. Generated, so it cannot drift from the stories, the decision log or
  the UAT script.

CONFIG
  argv[1]  the repository root. Needs gherkin-official (through uat/build_uat.py's parser).

WORKFLOW
  1 OBJECTIVES below: each objective and the stories that serve it (the only hand-kept link)
  2 decisions and their rules from decisions/decision-log.md ("rules R1, R3" in each record)
  3 stories, their decisions and their UAT rows from uat/build_uat.py's parser
  4 write working-papers/W08-traceability-matrix.md: one row per UAT row, with its objective, decisions, rules and
    refused move; then a summary per objective
  5 [CONTROL] refuse when an objective has no UAT row, a story serves no objective, or a story cites a decision the log
    does not have; the checks are shown able to fire on a planted objective and a planted decision first
  rc 0 ok . 2 usage . 3 a check failed

Q&A
  Q: why is the objective-to-story link typed by hand?   A: it is a judgement about purpose, and the only one here. Every
                                                            other link is read from the files that carry it.

PITFALLS
  UAT ids are positional (stories sorted by file name), so the matrix is rebuilt whenever a story changes.

NOTES
  Tanmark Industries is fictional.
"""
import io
import os
import re
import sys

OBJECTIVES = {
    "O1": ("Anyone who needs it can see where an order is", ["order-lifecycle", "order-closure", "sale-statuses"]),
    "O2": ("Stock in the system matches the shelves", ["order-closure", "delivery-trip", "purchase-order", "material-request"]),
    "O3": ("Orders are delivered faster, and collected on their terms", ["order-lifecycle", "delivery-trip", "receivables"]),
    "O4": ("The ledger can be audited", ["voucher-posting", "sale-statuses", "receivables"]),
    "O5": ("Purchasing is not slowed by a second approval", ["purchase-order"]),
}


def decision_rules(root):
    text = io.open(os.path.join(root, "decisions", "decision-log.md"), encoding="utf-8").read()
    out = {}
    for block in re.split(r"\n## ", text)[1:]:
        m = re.match(r"(D\d+)\.", block)
        if m:
            out[m.group(1)] = sorted(set(re.findall(r"\bR\d+\b", block)), key=lambda r: int(r[1:]))
    return out


def check(objectives, stories, decisions, rows):
    problems = []
    served = {s for _, ss in objectives.values() for s in ss}
    for oid, (_, ss) in objectives.items():
        if not any(r["story"] in ss for r in rows):
            problems.append("objective %s has no UAT row" % oid)
    for s in stories:
        if s not in served:
            problems.append("story %s serves no objective" % s)
    for r in rows:
        for d in re.findall(r"D\d+", r["decision"]):
            if d not in decisions:
                problems.append("%s cites %s, which the decision log does not have" % (r["id"], d))
    return sorted(set(problems))


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    root = argv[1]
    sys.path.insert(0, os.path.join(root, "uat"))
    from build_uat import parse
    rows, stories, _, _ = parse(root)
    story_names = [s for s, _, _ in stories]
    decisions = decision_rules(root)
    planted = dict(OBJECTIVES, O9=("planted", ["no-such-story"]))
    caught = check(planted, story_names, decisions, rows + [{"id": "UAT-X", "story": "x", "decision": "D99"}])
    ok = any("O9" in p for p in caught) and any("D99" in p for p in caught)
    print("[CONTROL] planted objective and decision caught: %s" % ok)
    problems = check(OBJECTIVES, story_names, decisions, rows)
    for p in problems:
        print("  PROBLEM " + p)
    ok = ok and not problems
    md = ["# W8. Requirements traceability matrix", "",
          "**Tanmark Industries is fictional.** **Generated by `working-papers/build_rtm.py`; do not edit by hand.** Each rule "
          "is read from the state model for the move the test exercises, not inferred from the decision.", "",
          "Each row is one UAT test. Read left to right: why it exists, which decision it enforces, which state rule it "
          "tests, and the refused move when it is an error path.", "",
          "| Objective | UAT | Story | Scenario | Decisions | Rule | State transition |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        objs = ", ".join(o for o, (_, ss) in OBJECTIVES.items() if r["story"] in ss)
        rules = [r["rule"]] if r["rule"] else []  # the rule the tested move enforces, from the model
        md.append("| %s | %s | %s | %s | %s | %s | %s |" % (objs, r["id"], r["story"], r["scenario"], r["decision"],
                                                            ", ".join(rules) or "none", r["transition"]))
    md += ["", "## Coverage by objective", "", "| Objective | UAT rows | Error paths |", "|---|---|---|"]
    for oid, (name, ss) in OBJECTIVES.items():
        mine = [r for r in rows if r["story"] in ss]
        md.append("| %s %s | %d | %d |" % (oid, name, len(mine), sum(1 for r in mine if r["refused"])))
    md += ["", "## Coverage by rule", "", "| Rule | UAT rows |", "|---|---|"]
    for rid in ["R%d" % k for k in range(1, 8)]:
        mine = [x["id"] for x in rows if x["rule"] == rid]
        md.append("| %s | %s |" % (rid, ", ".join(mine) if mine else "**none**: enforced by configuration, "
                                   "tested in the role checks (W5 N5), not by a story"))
    out = os.path.join(root, "working-papers", "W08-traceability-matrix.md")
    io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("rows %d . objectives %d . stories %d . decisions in the log %d" % (len(rows), len(OBJECTIVES),
                                                                             len(story_names), len(decisions)))
    print("[RESULT] %s -> %s" % ("ok" if ok else "REFUSED", out))
    return 0 if ok else 3


if __name__ == "__main__":
    sys.exit(main(sys.argv))
